export function topicById(id: string): TheoryTopic {
  const t = THEORY.find((x) => x.id === id)
  if (!t) throw new Error(`unknown theory topic ${id}`)
  return t
}

export function isTopicId(id: string): boolean {
  return THEORY.some((t) => t.id === id)
}

export function questionCount(): number {
  return THEORY.reduce((n, t) => n + t.questions.length, 0)
}
